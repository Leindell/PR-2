class PDF(FPDF):
    def footer(self):
        self.set_y(-15)
        self.set_font("dv", size=8)
        self.cell(0, 10, f"Внутренний документ. Страница {self.page_no()}", align="C")


def write_pdf(path, title, sections):
    pdf = PDF()
    pdf.add_font("dv", fname=FONT)
    pdf.add_font("dv", style="B", fname=FONT_B)
    pdf.add_page()
    pdf.set_font("dv", "B", 14)
    pdf.multi_cell(0, 8, title, new_x="LMARGIN", new_y="NEXT")
    for head, text in sections:
        pdf.ln(3)
        pdf.set_font("dv", "B", 12)
        pdf.multi_cell(0, 7, head, new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("dv", size=11)
        pdf.multi_cell(0, 6, text, new_x="LMARGIN", new_y="NEXT")
    pdf.output(str(path))


def write_docx(path, title, sections):
    d = Document()
    d.add_heading(title, level=0)
    for head, text in sections:
        d.add_heading(head, level=1)
        d.add_paragraph(text)
    d.save(str(path))


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    made = 0
    for name, (title, sections) in CORPUS.items():
        p = OUT / name
        if p.exists():
            continue
        (write_pdf if name.endswith(".pdf") else write_docx)(p, title, sections)
        made += 1
    print(f"make_docs: created {made}, total {len(CORPUS)} files in {OUT}")
