"""Стадия 5: подготовка входа для LLM - гибридный поиск + промпт с источниками.

Модель сюда не встроена (по заданию - подготовка данных, а не сама LLM): на выходе готовый промпт,
который отправляется в любую LLM. Пример: python ask.py "сколько суточных платят в командировке"
"""
import sys

from search import hybrid

q = " ".join(sys.argv[1:]) or "сколько суточных платят в командировке по России"
ctx = hybrid(q, k=4)
sources = "\n\n".join(f"[{i}] {r[1]} - {r[2]} ({r[4]})\n{r[3]}" for i, r in enumerate(ctx, 1))
print(f"""Ты - помощник по внутренним регламентам компании. Отвечай только по источникам ниже.
Если ответа в источниках нет - так и скажи. После каждого факта ставь номер источника [N].

Источники:
{sources}

Вопрос: {q}
Ответ:""")
